"""Render THIRD-PARTY-NOTICES.md from the locked components and their resolved licences.

The component list is the one a current release flavour resolves (`sbom.flavoured_lines`), not the
union with the retired bare configuration, so the notices describe what the APK contains. Each
component appears under every licence it is used under, with the publisher the POM names, and each
licence section states the obligation that licence imposes and points at its full text.

`check_notices.py` regenerates this file and fails on one byte of difference.
"""
import pathlib

import licences
from sbom import flavoured_lines

ROOT = pathlib.Path(__file__).resolve().parents[2]
LOCK = ROOT / "app" / "gradle.lockfile"
OUT = ROOT / "THIRD-PARTY-NOTICES.md"
TEXTS = ROOT / "tools" / "security" / "data" / "licences"

OBLIGATIONS = {
    licences.APACHE: "keep the copyright, patent, trademark and attribution notices, and pass on a "
                     "copy of the licence",
    licences.BSD: "retain the copyright notice, this list of conditions and the disclaimer, and do "
                  "not use the holder's name to endorse this product",
    licences.MIT: "keep the copyright notice and this permission notice with the component",
    licences.BOUNCY: "keep the Bouncy Castle copyright notice and this permission notice",
    licences.ANDROID: "proprietary Google terms: do not modify or extract the SDK, and do not imply "
                      "Google endorsement",
}

ELECTION_TEXT = """\
Two components offer a choice of grants. The choice this distribution makes, and relies on, is
recorded here so that it does not have to be inferred from a POM:

- `net.java.dev.jna:jna` is distributed under **Apache-2.0**, not LGPL-2.1-or-later. The upstream
  LICENSE states `SPDX-License-Identifier: Apache-2.0 OR LGPL-2.1-or-later` and "You can freely
  decide which of these licenses to apply to JNA's own code". This notice is that decision for
  every sign-setu build from this commit on: JNA is not used under the LGPL, so no source offer,
  relink duty or LGPL notice attaches to it or to the app.
- `org.checkerframework:checker-compat-qual` is distributed under **MIT**, not
  GPL-2.0-with-classpath-exception. It is an annotations-only jar, and the MIT grant imposes
  nothing beyond keeping its notice.
"""


def component_rows(lines, licence_map):
    """(licence group, group, artifact, version, attribution, entry) for each flavour-resolved line."""
    rows = []
    for line in flavoured_lines(lines):
        group, artifact, version = licences.split_coordinate(licences.coordinate(line))
        entry = licence_map.get(licences.coordinate(line)) or {}
        declared = entry.get("licences") or []
        if not declared:
            raise SystemExit(f"{group}:{artifact}:{version}: no resolved licence in data/licences.json")
        attribution = entry.get("attribution")
        if not attribution:
            attribution = next((PUBLISHERS[name] for name in declared if name in PUBLISHERS),
                               "not stated in the POM")
        rows.append((" / ".join(sorted(declared)), group, artifact, version, attribution, entry))
    return sorted(rows, key=lambda row: (row[0], row[1], row[2], row[3]))


PUBLISHERS = {
    licences.ANDROID: "Google LLC",
    licences.BOUNCY: "The Legion of the Bouncy Castle Inc.",
}

TEXT_FILES = {
    licences.APACHE: "apache-2.0.txt",
    licences.BSD: "bsd-3-clause.txt",
    licences.MIT: "mit.txt",
    licences.BOUNCY: "bouncy-castle.txt",
    licences.ANDROID: None,
}


def appendix(texts) -> str:
    """The full licence texts the sections cite, each under its own heading; `texts` is a dict."""
    out = []
    for number, (name, body) in enumerate(texts.items(), 1):
        out.append(f"### Appendix {number}: {name}\n")
        if body is None:
            out.append("The full terms are at https://developer.android.com/studio/terms.")
        else:
            out.append("```")
            out.append((TEXTS / body).read_text(encoding="utf-8").rstrip())
            out.append("```")
        out.append("")
    return "\n".join(out)


def render(lines, licence_map, version) -> str:
    """The notices document as text."""
    rows = component_rows(lines, licence_map)
    groups = {}
    for licence_key, group, artifact, ver, attribution, entry in rows:
        groups.setdefault(licence_key, []).append((group, artifact, ver, attribution, entry))

    out = [
        "# Third-party notices\n",
        f"sign-setu {version} bundles the {len(rows)} third-party components below. The list is the "
        "resolved release runtime classpath in `app/gradle.lockfile`, restricted to the configurations "
        "a current release flavour resolves.\n",
        "This file is generated by `tools/security/notices.py` from the licence resolution in "
        "`tools/security/data/licences.json`. `python tools/security/check_notices.py` fails when this "
        "file and that resolution disagree.\n",
        "## Licence elections\n",
        ELECTION_TEXT,
        "## Components by licence\n",
    ]

    texts = {}
    for licence_key in sorted(groups):
        names = licence_key.split(" / ")
        count = len(groups[licence_key])
        out.append(f"### {licence_key} ({count} component{'' if count == 1 else 's'})\n")
        duties = [OBLIGATIONS[name] for name in names if name in OBLIGATIONS]
        if duties:
            out.append("Each component here is used under this licence. The obligation is to "
                       + "; ".join(duties) + ".\n")
        for name in names:
            if name in TEXT_FILES:
                texts.setdefault(name, TEXT_FILES[name])
        out.append("| Component | Version | Attribution |")
        out.append("| --- | --- | --- |")
        for group, artifact, ver, attribution, entry in groups[licence_key]:
            elected = (entry.get("election") or {}).get("elected")
            note = f" (elected grant: {elected})" if elected else ""
            out.append(f"| `{group}:{artifact}`{note} | {ver} | {attribution} |")
        out.append("")
        cited = [f"Appendix {number}" for number, name in enumerate(texts, 1) if name in names]
        if cited:
            out.append("Full text: " + ", ".join(cited) + ".\n")
        elif duties:
            out.append("The grant is stated in each component's own POM and artifact.\n")

    out.append("## Licence texts\n")
    out.append(appendix(texts))
    return "\n".join(out).rstrip() + "\n"


def main(lines=None, out=OUT, licence_map=None, version=None) -> int:
    """Write the notices file and report the component count."""
    import sbom_lockfile

    lines = LOCK.read_text(encoding="utf-8").splitlines() if lines is None else lines
    licence_map = licences.load() if licence_map is None else licence_map
    version = version or sbom_lockfile.project_version()
    text = render(lines, licence_map, version)
    out.write_text(text, encoding="utf-8", newline="\n")
    covered = sum(1 for line in flavoured_lines(lines))
    print(f"{covered} shipped components -> {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
